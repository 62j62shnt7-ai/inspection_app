def _parse_float_or_none(val):
    """Parse a value as a pure float, else None.

    Engineering fields must be numeric to drive POF/interval logic — text like
    '1st insp.' is NOT a remaining life of 1 year.
    """
    if val is None:
        return None
    s = str(val).strip()
    if not re.fullmatch(r"-?\d+(?:\.\d+)?", s):
        return None
    try:
        return float(s)
    except ValueError:
        return None

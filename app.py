# Campaign scope strings that mean a SHUTDOWN (internal) inspection.
# Everything else ('OSI', 'OSI-ADV', 'UT + VT', 'PT + VT', blank) is on-stream.
INTERNAL_SCOPE_KEYWORDS = ("INTERNAL", "SD", "NSD")


def _is_internal_scope(scope_category):
    """Classify a campaign scope string as internal (shutdown) vs on-stream.

    Matches the full-scope vocabulary in refined plan.xlsx: 'SD/Internal',
    'NSD/Internal', 'Internal' are shutdown scopes; 'OSI', 'OSI-ADV',
    'UT + VT', 'PT + VT' are on-stream.
    """
    s = (scope_category or "").upper()
    return any(k in s for k in INTERNAL_SCOPE_KEYWORDS)


def api_sync_completed_to_master():
    """
    Bulk synchronize completed inspections from the reconciled campaign into the Master Plan.
    Logs official inspection records in inspection_log, advances statutory inspection dates,
    clears overdue status for equipment completed in the field, and updates refined_plan_items.
    """
    backup = _backup_db()
    today_iso = datetime.date.today().isoformat()
    synced_count = 0
    updated_assets = set()
    api_sync_completed_to_master._adjusted = 0

    with CONN_LOCK:
        # Ensure migration columns exist
        try:
            CONN.execute("ALTER TABLE refined_plan_items ADD COLUMN synced_to_master INTEGER DEFAULT 0")
        except Exception:
            pass
        try:
            CONN.execute("ALTER TABLE refined_plan_items ADD COLUMN synced_at TEXT")
        except Exception:
            pass

        items = CONN.execute("""
            SELECT id, asset_id, pkg_or_asset_no, item_description,
                   last_insp_date, planned_insp_date, scope_category,
                   ut_progress, report_issued, remarks
            FROM refined_plan_items
            WHERE asset_id IS NOT NULL
              AND synced_to_master = 0
              AND (
                LOWER(ut_progress) LIKE '%done%' OR 
                LOWER(report_issued) LIKE '%done%' OR
                LOWER(ut_progress) LIKE '%completed%'
              )
              AND NOT (
                COALESCE(ut_progress, '') LIKE '%out of%' OR COALESCE(report_issued, '') LIKE '%out of%'
                OR COALESCE(ut_progress, '') LIKE '%replaced%' OR COALESCE(report_issued, '') LIKE '%replaced%'
                OR COALESCE(ut_progress, '') LIKE '%tubing%' OR COALESCE(report_issued, '') LIKE '%tubing%'
              )
        """).fetchall()

        for item in items:
            item_id = item["id"]
            asset_id = item["asset_id"]
            is_internal = _is_internal_scope(item["scope_category"])
            insp_type = "Internal" if is_internal else "OSI"

            # The inspection that completed is the CAMPAIGN inspection!
            # Use planned_insp_date if available (e.g. 2025-02-01), or today
            insp_date = item["planned_insp_date"] or today_iso
            try:
                dt = datetime.date.fromisoformat(insp_date)
            except Exception:
                dt = datetime.date.today()
                insp_date = dt.isoformat()

            # Prevent duplicate logs for the same asset and date
            existing = CONN.execute(
                "SELECT id FROM inspection_log WHERE asset_id = ? AND insp_date = ?",
                (asset_id, insp_date)
            ).fetchone()

            # Interval selection: statutory default (10y internal / 5y OSI),
            # but never extend beyond the asset's credible remaining life.
            # A fixed 10-year date on an asset with RL 4y would schedule an
            # inspection past end of life.
            interval_years = 10 if is_internal else 5
            interval_note = "statutory default"
            asset_row = CONN.execute(
                "SELECT corrosion_rate, remaining_life FROM assets WHERE id = ?", (asset_id,)).fetchone()
            rl_val = _parse_float_or_none(asset_row["remaining_life"]) if asset_row else None
            cr_val = _parse_float_or_none(asset_row["corrosion_rate"]) if asset_row else None
            if rl_val is not None and rl_val > 0:
                half_life = max(1.0, rl_val / 2.0)
                if half_life < interval_years:
                    interval_years = round(half_life, 1)
                    interval_note = f"capped at half of stored remaining life ({rl_val}y)"
            elif cr_val is not None and cr_val >= 0.25:
                interval_years = min(interval_years, 5.0)
                interval_note = f"capped by high corrosion rate ({cr_val} mm/yr)"
            adjusted_intervals = getattr(api_sync_completed_to_master, "_adjusted", 0)
            if interval_note != "statutory default":
                adjusted_intervals += 1
                api_sync_completed_to_master._adjusted = adjusted_intervals

            try:
                calc_next = (dt + datetime.timedelta(days=int(interval_years * 365.25))).isoformat()
            except (ValueError, OverflowError):
                calc_next = (dt + datetime.timedelta(days=int(interval_years * 365.25))).isoformat()

            if not existing:
                findings = f"Campaign UT Inspection: Done. Report: {item['report_issued'] or 'Issued'}. Scope: {item['scope_category'] or 'UT/VT'}."
                if item["remarks"]:
                    findings += f" | {item['remarks']}"

                CONN.execute("""
                    INSERT INTO inspection_log (
                        asset_id, insp_date, insp_type, findings,
                        next_due_date, inspector_name, insp_method
                    ) VALUES (?, ?, ?, ?, ?, ?, ?)
                """, (
                    asset_id, insp_date, insp_type, findings,
                    calc_next, "Tactical Inspection Team", item["scope_category"] or "UT / VT"
                ))

            # Update asset statutory dates and advance next due date (officially clears overdue!)
            # Only advance the specific statutory track this scope covers, and
            # never move the date BACKWARDS (an older campaign record re-synced
            # later must not regress an already-advanced schedule).
            if is_internal:
                CONN.execute("""
                    UPDATE assets 
                    SET date_internal_last = MAX(COALESCE(date_internal_last, ''), ?),
                        date_internal_next = MAX(COALESCE(date_internal_next, ''), ?),
                        status_internal_next = 'Scheduled'
                    WHERE id = ?
                """, (insp_date, calc_next, asset_id))
            else:
                CONN.execute("""
                    UPDATE assets 
                    SET date_osi_last = MAX(COALESCE(date_osi_last, ''), ?),
                        date_osi_next = MAX(COALESCE(date_osi_next, ''), ?),
                        status_osi_next = 'Scheduled'
                    WHERE id = ?
                """, (insp_date, calc_next, asset_id))

            # Mark campaign item as synced to master. KEEP the original
            # plan-vs-statutory baseline variance: overwriting it with
            # planned-minus-new-next-due would report a fake -3650d for
            # every 10y-interval asset and destroy the reconciliation KPIs.
            CONN.execute("""
                UPDATE refined_plan_items
                SET synced_to_master = 1, synced_at = datetime('now')
                WHERE id = ?
            """, (item_id,))

            synced_count += 1
            updated_assets.add(asset_id)

        CONN.commit()

    adjusted = getattr(api_sync_completed_to_master, "_adjusted", 0)
    _audit("sync_completed_to_master", "refined_plan_items", None, {
        "synced_count": synced_count,
        "assets_updated": len(updated_assets),
        "intervals_adjusted_for_rl": adjusted,
        "backup_file": backup,
    })

    note = (f" {adjusted} interval(s) were shortened based on remaining life / corrosion rate."
            if adjusted else "")
    return {
        "ok": True,
        "message": (f"Successfully synchronized {synced_count} campaign inspections to Master Plan "
                    f"({len(updated_assets)} assets updated). Statutory dates advanced and overdue "
                    f"statuses cleared.{note}"),
        "synced_count": synced_count,
        "assets_updated": len(updated_assets),
        "intervals_adjusted": adjusted,
        "backup_file": backup
    }


